	public static PanelLanguage Current = PanelLanguage.Ru;

	public static int Generation;

	private static readonly Dictionary<PanelLanguage, Dictionary<string, string>> Table = new Dictionary<PanelLanguage, Dictionary<string, string>>
	{
		[PanelLanguage.Ru] = Ru(),
		[PanelLanguage.En] = En(),
		[PanelLanguage.Es] = Es()
	};

	public static string GameCode => Current switch
	{
		PanelLanguage.En => "en", 
		PanelLanguage.Es => "es", 
		_ => "ru", 
	};

	public static string T(string key)
	{
		if (Table.TryGetValue(Current, out var value) && value.TryGetValue(key, out var value2))
		{
			return value2;
		}
		if (Table[PanelLanguage.En].TryGetValue(key, out var value3))
		{
			return value3;
		}
		return key;
	}

	public static string F(string key, params object[] args)
	{
		return string.Format(T(key), args);
	}

	public static void Set(PanelLanguage lang)
	{
		if (Current != lang)
		{
			Current = lang;
			Generation++;
			if (CheatConfig.UiLanguage != null)
			{
				CheatConfig.UiLanguage.Value = lang;
			}
		}
	}

